"""Export a checkpoint to the INT8 C-engine blob and the tokenizer blob.

python -m microcoder.export ckpt/m1_s0.pt export/   ->  model.bin, tok.bin, model_data.h
"""
import json, os, struct, sys
import numpy as np
import torch
from tokenizers import Tokenizer
from tokenizers.pre_tokenizers import ByteLevel

MAGIC_M, MAGIC_T = 0x3143434D, 0x3154434D


def pad4(b):
    return b + b"\0" * ((-len(b)) % 4)


def q8(w):
    w = w.detach().float().numpy()
    s = np.abs(w).max(1) / 127.0
    s[s == 0] = 1e-12
    q = np.clip(np.round(w / s[:, None]), -127, 127).astype(np.int8)
    return pad4(q.tobytes()) + pad4(s.astype(np.float32).tobytes())


def f32(w):
    return pad4(w.detach().float().numpy().astype(np.float32).tobytes())


def export_model(ck):
    sd, c = ck["model"], ck["cfg"]
    out = struct.pack("<8i", MAGIC_M, c["vocab"], c["d"], c["layers"], c["heads"], c["ff_mult"] * c["d"] // c["d"], c["ctx"], 0)
    out += q8(sd["emb.weight"]) + f32(sd["nf.w"])
    for l in range(c["layers"]):
        p = f"blocks.{l}."
        out += f32(sd[p + "n1.w"]) + f32(sd[p + "n2.w"])
        out += q8(sd[p + "qkv.weight"]) + q8(sd[p + "o.weight"]) + q8(sd[p + "up.weight"]) + q8(sd[p + "down.weight"])
    return out


def byte_decoder():
    # inverse of the GPT-2 bytes->unicode table used by ByteLevel
    bs = list(range(ord("!"), ord("~") + 1)) + list(range(ord("¡"), ord("¬") + 1)) + list(range(ord("®"), ord("ÿ") + 1))
    cs = bs[:]
    n = 0
    for b in range(256):
        if b not in bs:
            bs.append(b); cs.append(256 + n); n += 1
    return {chr(c): b for b, c in zip(bs, cs)}


def export_tok(path):
    j = json.load(open(path))
    vocab = j["model"]["vocab"]
    added = {a["content"]: a["id"] for a in j["added_tokens"]}
    V = max(list(vocab.values()) + list(added.values())) + 1
    bd = byte_decoder()
    pieces = [b""] * V
    for s, i in vocab.items():
        pieces[i] = bytes(bd[ch] for ch in s) if s not in added else b""
    merges = j["model"]["merges"]
    trip = []
    for m in merges:
        a, b = m.split(" ") if isinstance(m, str) else m
        trip += [vocab[a], vocab[b], vocab[a + b]]
    offs, acc = [0], 0
    for p in pieces:
        acc += len(p); offs.append(acc)
    out = struct.pack("<8i", MAGIC_T, V, len(merges), added["<q>"], added["<c>"], added["<b>"], added["<r>"], added["<e>"])
    out += pad4(struct.pack(f"<{V + 1}I", *offs)) + pad4(b"".join(pieces)) + pad4(struct.pack(f"<{len(trip)}i", *trip))
    return out


def c_array(name, data):
    lines = [f"/* generated by microcoder.export — {len(data)} bytes */",
             f"#include <stdint.h>", f"__attribute__((aligned(4))) const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"const unsigned int {name}_len = {len(data)};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ck = torch.load(sys.argv[1])
    od = sys.argv[2]
    os.makedirs(od, exist_ok=True)
    mb, tb = export_model(ck), export_tok(ck["args"]["tok"])
    open(os.path.join(od, "model.bin"), "wb").write(mb)
    open(os.path.join(od, "tok.bin"), "wb").write(tb)
    if "--c" in sys.argv:
        open(os.path.join(od, "model_data.c"), "w").write(c_array("mc_model_blob", mb) + c_array("mc_tok_blob", tb))
    print(f"model.bin {len(mb)} bytes, tok.bin {len(tb)} bytes")
