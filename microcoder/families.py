"""Task families for the MicroCoder edge benchmark.

A *family* is a parameterised programming task: a set of natural-language
phrasings, a canonical reference solution template, and a test-input
generator. Concrete *tasks* are drawn by sampling a function name, argument
names and numeric constants. Expected outputs are always computed by running
the reference solution, never written by hand.

Families are split into TRAIN families and HELD-OUT families (never seen in
training) so that we can measure generalisation to unseen task templates, not
just memorisation. See dataset.py for the split.
"""

R = lambda lo, hi: (lambda rng: rng.randint(lo, hi))


def _floats(rng, n, lo=-50.0, hi=150.0):
    return [round(rng.uniform(lo, hi), 2) for _ in range(n)]


def _ints(rng, n, lo=-20, hi=100):
    return [rng.randint(lo, hi) for _ in range(n)]


def _list_tests(rng, lo=-20, hi=100, minlen=1, maxlen=8, k=5):
    return [(_ints(rng, rng.randint(minlen, maxlen), lo, hi),) for _ in range(k)]


def _flist_tests(rng, minlen=1, maxlen=8, k=5):
    return [(_floats(rng, rng.randint(minlen, maxlen)),) for _ in range(k)]


